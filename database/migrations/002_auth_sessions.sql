CREATE TABLE T_PE_SESSAO (
    DS_TOKEN_HASH VARCHAR2(64) NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    DT_EXPIRACAO TIMESTAMP NOT NULL,
    CONSTRAINT PK_PE_SESSAO PRIMARY KEY (DS_TOKEN_HASH),
    CONSTRAINT FK_PE_SESSAO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES T_PE_USUARIO (ID_USUARIO) ON DELETE CASCADE
);

CREATE INDEX IDX_PE_SESSAO_EXPIRACAO ON T_PE_SESSAO (DT_EXPIRACAO);
