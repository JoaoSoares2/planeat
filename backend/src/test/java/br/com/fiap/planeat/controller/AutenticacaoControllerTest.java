package br.com.fiap.planeat.controller;

import br.com.fiap.planeat.factory.ConnectionFactory;
import br.com.fiap.planeat.security.SessionManager;
import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.net.InetSocketAddress;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.sql.Timestamp;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.time.Instant;
import java.util.Base64;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AutenticacaoControllerTest {
    private HttpServer server;
    private HttpClient client;
    private URI baseUri;

    @BeforeEach
    void startServer() throws Exception {
        String databaseName = "planeat_auth_" + System.nanoTime();
        ConnectionFactory.setCredentials("jdbc:h2:mem:" + databaseName + ";MODE=Oracle;DB_CLOSE_DELAY=-1", "sa", "");
        try (Connection connection = ConnectionFactory.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE T_PE_USUARIO (ID_USUARIO BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NM_USUARIO VARCHAR(100) NOT NULL, DS_EMAIL VARCHAR(100) NOT NULL, DS_SENHA VARCHAR(255) NOT NULL, DT_CADASTRO DATE NOT NULL)");
            statement.execute("CREATE TABLE T_PE_SESSAO (DS_TOKEN_HASH VARCHAR(64) PRIMARY KEY, ID_USUARIO BIGINT NOT NULL, DT_EXPIRACAO TIMESTAMP NOT NULL, FOREIGN KEY (ID_USUARIO) REFERENCES T_PE_USUARIO(ID_USUARIO) ON DELETE CASCADE)");
        }
        server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/api/auth", new AutenticacaoController(new SessionManager(false)));
        server.start();
        client = HttpClient.newHttpClient();
        baseUri = URI.create("http://127.0.0.1:" + server.getAddress().getPort() + "/api/auth");
    }

    @AfterEach
    void stopServer() {
        if (server != null) server.stop(0);
        ConnectionFactory.resetCredentials();
    }

    @Test
    void registrationLoginSessionAndLogoutAreValidatedByTheServer() throws Exception {
        HttpResponse<String> anaCadastro = post("/cadastro",
                "{\"nome\":\"Ana Silva\",\"email\":\"ANA@example.com\",\"senha\":\"senha-segura\"}", null);
        HttpResponse<String> biaCadastro = post("/cadastro",
                "{\"nome\":\"Bia Souza\",\"email\":\"bia@example.com\",\"senha\":\"outra-senha\"}", null);
        assertEquals(201, anaCadastro.statusCode());
        assertEquals(201, biaCadastro.statusCode());
        assertFalse(anaCadastro.body().contains("senha-segura"));

        HttpResponse<String> loginInvalido = post("/login",
                "{\"email\":\"ana@example.com\",\"senha\":\"incorreta\"}", null);
        assertEquals(401, loginInvalido.statusCode());

        HttpResponse<String> loginAna = post("/login",
                "{\"email\":\"ana@example.com\",\"senha\":\"senha-segura\"}", null);
        HttpResponse<String> loginBia = post("/login",
                "{\"email\":\"bia@example.com\",\"senha\":\"outra-senha\"}", null);
        assertEquals(200, loginAna.statusCode());
        assertEquals(200, loginBia.statusCode());
        assertNotEquals(cookieValue(loginAna), cookieValue(loginBia));

        String anaCookie = cookieValue(loginAna);
        HttpResponse<String> sessao = get("/sessao", anaCookie);
        assertEquals(200, sessao.statusCode());
        assertTrue(sessao.body().contains("ana@example.com"));
        assertFalse(sessao.body().contains("senha"));

        HttpResponse<String> logout = post("/logout", "{}", anaCookie);
        assertEquals(204, logout.statusCode());
        assertEquals(401, get("/sessao", anaCookie).statusCode());
    }

    @Test
    void duplicateEmailsAreRejectedIgnoringLetterCase() throws Exception {
        assertEquals(201, post("/cadastro",
                "{\"nome\":\"Ana Silva\",\"email\":\"ana@example.com\",\"senha\":\"senha-segura\"}", null).statusCode());
        assertEquals(409, post("/cadastro",
                "{\"nome\":\"Outra Ana\",\"email\":\"ANA@example.com\",\"senha\":\"outra-senha\"}", null).statusCode());
    }

    @Test
    void expiredSessionIsRejectedByTheServer() throws Exception {
        post("/cadastro", "{\"nome\":\"Ana Silva\",\"email\":\"ana@example.com\",\"senha\":\"senha-segura\"}", null);
        String cookie = cookieValue(post("/login",
                "{\"email\":\"ana@example.com\",\"senha\":\"senha-segura\"}", null));
        String token = cookie.substring(cookie.indexOf('=') + 1);
        byte[] digest = MessageDigest.getInstance("SHA-256").digest(token.getBytes(StandardCharsets.UTF_8));
        String tokenHash = Base64.getUrlEncoder().withoutPadding().encodeToString(digest);
        try (Connection connection = ConnectionFactory.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     "UPDATE T_PE_SESSAO SET DT_EXPIRACAO = ? WHERE DS_TOKEN_HASH = ?")) {
            statement.setTimestamp(1, Timestamp.from(Instant.now().minusSeconds(1)));
            statement.setString(2, tokenHash);
            assertEquals(1, statement.executeUpdate());
        }

        assertEquals(401, get("/sessao", cookie).statusCode());
    }

    private HttpResponse<String> post(String path, String body, String cookie) throws Exception {
        HttpRequest.Builder request = HttpRequest.newBuilder(baseUri.resolve(baseUri.getPath() + path))
                .header("Content-Type", "application/json")
                .header("X-Requested-With", "XMLHttpRequest")
                .header("Origin", "http://localhost:5173")
                .POST(HttpRequest.BodyPublishers.ofString(body));
        if (cookie != null) request.header("Cookie", cookie);
        return client.send(request.build(), HttpResponse.BodyHandlers.ofString());
    }

    private HttpResponse<String> get(String path, String cookie) throws Exception {
        return client.send(HttpRequest.newBuilder(baseUri.resolve(baseUri.getPath() + path))
                        .header("X-Requested-With", "XMLHttpRequest")
                        .header("Cookie", cookie)
                        .GET()
                        .build(),
                HttpResponse.BodyHandlers.ofString());
    }

    private String cookieValue(HttpResponse<String> response) {
        return response.headers().firstValue("Set-Cookie").orElseThrow().split(";", 2)[0];
    }
}
